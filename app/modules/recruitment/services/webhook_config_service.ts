import { randomBytes } from 'node:crypto'
import encryption from '@adonisjs/core/services/encryption'
import type User from '#models/user'
import type RecruitmentWebhookConfig from '#models/recruitment_webhook_config'
import type { WebhookEnv } from '#models/recruitment_webhook_config'
import { AppException } from '#shared/exceptions/app_exception'
import auditService, { type AuditContext } from '#shared/audit/audit_service'
import { withTenant } from '#shared/tenant/with_tenant'
import type { TenantContext } from '#shared/tenant/tenant_context'
import outbound, { assertOutboundUrlShape, OutboundUrlError } from '#shared/http/outbound'
import { webhookConfigIn } from '#modules/recruitment/repositories/webhook_config_repository'

export interface WebhookConfigInput {
  testWebhookUrl?: string | null
  prodWebhookUrl?: string | null
  activeEnv?: WebhookEnv
  rotateSecret?: boolean
}

/** Purpose bound to the encrypted secret: it cannot be decrypted as anything else. */
const SECRET_PURPOSE = 'recruitment_webhook_secret'

const invalidUrl = (field: string, reason: string) =>
  AppException.validation(field, `url_${reason}`, 'validation.recruitment.webhookUrl')

/**
 * n8n webhook settings (docs/backend/06 §8, 08 §5, 05 §10): owner and
 * hr_admin only. The HMAC secret is generated by the server, stored
 * encrypted, and shown once, in the response that creates or rotates it.
 */
export class WebhookConfigService {
  show(tenant: TenantContext) {
    const { organizationId } = tenant
    return withTenant(organizationId, (trx) => webhookConfigIn(organizationId, trx).find())
  }

  async update(
    tenant: TenantContext,
    actor: User,
    input: WebhookConfigInput,
    audit: AuditContext
  ): Promise<{ config: RecruitmentWebhookConfig; secret: string | null }> {
    for (const field of ['testWebhookUrl', 'prodWebhookUrl'] as const) {
      const url = input[field]
      if (!url) continue
      try {
        assertOutboundUrlShape(url)
      } catch (error) {
        if (error instanceof OutboundUrlError) throw invalidUrl(field, error.message)
        throw error
      }
    }
    const { organizationId } = tenant
    return withTenant(organizationId, async (trx) => {
      const configs = webhookConfigIn(organizationId, trx)
      const config = await configs.findOrNew()
      if (input.testWebhookUrl !== undefined) config.testWebhookUrl = input.testWebhookUrl
      if (input.prodWebhookUrl !== undefined) config.prodWebhookUrl = input.prodWebhookUrl
      if (input.activeEnv !== undefined) config.activeEnv = input.activeEnv
      if (config.activeEnv !== 'off' && !this.urlOf(config, config.activeEnv)) {
        throw AppException.validation('activeEnv', 'url', 'validation.recruitment.webhookEnvUrl')
      }
      let secret: string | null = null
      if (!config.secretEncrypted || input.rotateSecret) {
        secret = randomBytes(32).toString('hex')
        config.secretEncrypted = encryption.encrypt(secret, undefined, SECRET_PURPOSE)
      }
      config.updatedBy = actor.id
      await configs.save(config)
      await auditService.record(
        trx,
        { ...audit, organizationId, actorRole: tenant.primaryRole },
        {
          action: 'recruitment_webhook.updated',
          targetType: 'recruitment_webhook_config',
          targetId: organizationId,
          after: { activeEnv: config.activeEnv, secretRotated: secret !== null },
        }
      )
      await config.refresh()
      return { config, secret }
    })
  }

  /** `POST /webhooks/ping`: a signed `webhook.ping` and its diagnosis (08 §5). */
  async ping(tenant: TenantContext, env: Exclude<WebhookEnv, 'off'> | undefined) {
    const config = await this.show(tenant)
    const target = env ?? (config?.activeEnv === 'off' ? undefined : config?.activeEnv)
    const url = config && target ? this.urlOf(config, target) : null
    const secret = config ? this.secretOf(config) : null
    if (!target || !url || !secret) {
      throw AppException.validation(
        'env',
        'configured',
        'validation.recruitment.webhookNotConfigured'
      )
    }
    const result = await outbound.postSigned(
      url,
      {
        event: 'webhook.ping',
        organizationId: tenant.organizationId,
        sentAt: new Date().toISOString(),
      },
      secret
    )
    const ok = result.error === null && result.status !== null && result.status < 300
    return {
      env: target,
      ok,
      status: result.status,
      latencyMs: result.latencyMs,
      error: result.error,
    }
  }

  urlOf(config: RecruitmentWebhookConfig, env: Exclude<WebhookEnv, 'off'>) {
    return env === 'test' ? config.testWebhookUrl : config.prodWebhookUrl
  }

  /** The clear secret, for signing; `null` when absent or unreadable. */
  secretOf(config: RecruitmentWebhookConfig): string | null {
    if (!config.secretEncrypted) return null
    return encryption.decrypt<string>(config.secretEncrypted, SECRET_PURPOSE)
  }
}

export default new WebhookConfigService()
