import type { HttpContext } from '@adonisjs/core/http'
import { ApiBody, ApiOperation } from '@foadonis/openapi/decorators'
import RecruitmentPolicy from '#policies/recruitment_policy'
import jobService from '#modules/recruitment/services/job_service'
import { jobDto } from '#modules/recruitment/transformers/recruitment_transformer'
import { pageMetaDto } from '#modules/hr/transformers/hr_transformer'
import {
  createJobValidator,
  generateJobValidator,
  jobIdValidator,
  listJobsValidator,
  updateJobValidator,
} from '#modules/recruitment/validators/job_validator'
import { auditContext } from '#modules/auth/http_helpers'

/** `/api/v1/org/recruitment/jobs` (06-api-reference §8, 07 §4.1). */
export default class JobsController {
  @ApiOperation({ summary: 'List the job offers visible to the caller' })
  async index(ctx: HttpContext) {
    const query = await ctx.request.validateUsing(listJobsValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('listJobs')
    const { rows, meta } = await jobService.list(ctx.tenant, query)
    return { data: rows.map(jobDto), meta: pageMetaDto(meta) }
  }

  @ApiOperation({ summary: 'Create a draft job offer (slug generated by the server)' })
  @ApiBody({ type: () => createJobValidator })
  async store(ctx: HttpContext) {
    const input = await ctx.request.validateUsing(createJobValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const job = await jobService.create(
      ctx.tenant,
      ctx.auth.getUserOrFail(),
      input,
      auditContext(ctx)
    )
    ctx.response.status(201)
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'Job offer detail' })
  async show(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    const { job, inDepartment } = await jobService.find(ctx.tenant, params.id)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('viewJob', inDepartment)
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'Update a job offer' })
  @ApiBody({ type: () => updateJobValidator })
  async update(ctx: HttpContext) {
    const { params, ...input } = await ctx.request.validateUsing(updateJobValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const job = await jobService.update(
      ctx.tenant,
      ctx.auth.getUserOrFail(),
      params.id,
      input,
      auditContext(ctx)
    )
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'Delete a job offer (soft delete)' })
  async destroy(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    await jobService.remove(ctx.tenant, ctx.auth.getUserOrFail(), params.id, auditContext(ctx))
    return ctx.response.noContent()
  }

  @ApiOperation({ summary: 'Publish a draft or closed offer' })
  async publish(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const job = await jobService.publish(
      ctx.tenant,
      ctx.auth.getUserOrFail(),
      params.id,
      auditContext(ctx)
    )
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'Close a published offer' })
  async close(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const job = await jobService.close(
      ctx.tenant,
      ctx.auth.getUserOrFail(),
      params.id,
      auditContext(ctx)
    )
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'Duplicate an offer as a new draft' })
  async duplicate(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const job = await jobService.duplicate(
      ctx.tenant,
      ctx.auth.getUserOrFail(),
      params.id,
      auditContext(ctx)
    )
    ctx.response.status(201)
    return ctx.serialize(jobDto(job))
  }

  @ApiOperation({ summary: 'AI description and requirements of the offer (one AI credit)' })
  @ApiBody({ type: () => generateJobValidator })
  async generate(ctx: HttpContext) {
    const { params, ...input } = await ctx.request.validateUsing(generateJobValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const result = await jobService.generate(ctx.tenant, ctx.auth.getUserOrFail(), params.id, input)
    return ctx.serialize(result)
  }

  @ApiOperation({ summary: 'QR code (PNG) of the public page of the offer' })
  async qr(ctx: HttpContext) {
    const { params } = await ctx.request.validateUsing(jobIdValidator)
    await ctx.bouncer.with(RecruitmentPolicy).authorize('manageJobs')
    const { job } = await jobService.find(ctx.tenant, params.id)
    const png = await jobService.qr(ctx.tenant, job)
    ctx.response.header('Content-Type', 'image/png')
    ctx.response.header('Cache-Control', 'private, max-age=300')
    return ctx.response.send(png)
  }
}
