import vine from '@vinejs/vine'

const CONTRACT_TYPES = ['cdi', 'cdd', 'stage', 'freelance', 'apprenticeship', 'daily'] as const
const STATUSES = ['draft', 'published', 'closed', 'archived'] as const

const params = () => vine.object({ id: vine.string().uuid() })

/** Extra pieces of an application (decision of 2026-11-23): `[{ key, label, required }]`. */
const requiredDocuments = () =>
  vine
    .array(
      vine.object({
        key: vine
          .string()
          .trim()
          .regex(/^[a-z][a-z0-9_]{0,39}$/),
        label: vine.string().trim().minLength(1).maxLength(120),
        required: vine.boolean(),
      })
    )
    .maxLength(10)

const optionalFields = {
  departmentId: vine.string().uuid().nullable().optional(),
  location: vine.string().trim().maxLength(200).nullable().optional(),
  description: vine.string().trim().maxLength(20_000).nullable().optional(),
  requirements: vine.string().trim().maxLength(20_000).nullable().optional(),
  deadline: vine
    .date({ formats: ['iso8601'] })
    .nullable()
    .optional(),
  requiredDocuments: requiredDocuments().optional(),
}

export const jobIdValidator = vine.create({ params: params() })

export const listJobsValidator = vine.create({
  page: vine.number().withoutDecimals().min(1).max(10_000).optional(),
  perPage: vine.number().withoutDecimals().min(1).max(100).optional(),
  q: vine.string().trim().minLength(1).maxLength(100).optional(),
  filter: vine
    .object({
      status: vine.enum(STATUSES).optional(),
      departmentId: vine.string().uuid().optional(),
    })
    .optional(),
})

/** POST /org/recruitment/jobs: the slug is always generated by the server (05 §2). */
export const createJobValidator = vine.create({
  title: vine.string().trim().minLength(2).maxLength(200),
  contractType: vine.enum(CONTRACT_TYPES),
  ...optionalFields,
})

export const updateJobValidator = vine.create({
  params: params(),
  title: vine.string().trim().minLength(2).maxLength(200).optional(),
  contractType: vine.enum(CONTRACT_TYPES).optional(),
  ...optionalFields,
})

/** Public routes: slugs as generated (lower-case letters, digits, dashes). */
const slug = () =>
  vine
    .string()
    .trim()
    .maxLength(80)
    .regex(/^[a-z0-9-]+$/)

export const careersPageValidator = vine.create({ params: vine.object({ orgSlug: slug() }) })

export const careersJobValidator = vine.create({
  params: vine.object({ orgSlug: slug(), jobSlug: slug() }),
})
